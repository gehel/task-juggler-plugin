import org.jetbrains.intellij.platform.gradle.TestFrameworkType
import org.jetbrains.intellij.platform.gradle.tasks.GenerateLexerTask
import org.jetbrains.intellij.platform.gradle.tasks.GenerateParserTask

plugins {
    java
    id("org.jetbrains.intellij.platform") version "2.20.1"
    id("org.jetbrains.intellij.platform.grammarkit") version "2.20.1"
}

group = "fr.ledcom.tj3"
version = providers.gradleProperty("pluginVersion").get()

java {
    toolchain {
        languageVersion.set(JavaLanguageVersion.of(25))
    }
}

repositories {
    mavenCentral()
    intellijPlatform {
        defaultRepositories()
    }
}

// Lexer and parser are generated by Grammar-Kit from src/main/grammars (see generateTJLexer / generateTJParser).
// Separate output roots: each task purges its whole output root before generating.
val generatedLexerRoot = layout.buildDirectory.dir("generated/sources/grammarkit/lexer")
val generatedParserRoot = layout.buildDirectory.dir("generated/sources/grammarkit/parser")

sourceSets {
    main {
        java {
            srcDir(generatedLexerRoot)
            srcDir(generatedParserRoot)
        }
    }
}

// Configure IntelliJ Platform Gradle Plugin
// Read more: https://plugins.jetbrains.com/docs/intellij/tools-intellij-platform-gradle-plugin.html
dependencies {
    intellijPlatform {
        intellijIdea("2026.2.5")
        testFramework(TestFrameworkType.Platform)
    }
    testImplementation("junit:junit:4.13.2")
    testImplementation("org.opentest4j:opentest4j:1.3.0")
}

intellijPlatform {
    pluginConfiguration {
        ideaVersion {
            sinceBuild = "262"
        }

        changeNotes = """
            First public release: highlighting, completion, navigation, quick documentation, inspections,
            formatter, structure view and tj3 integration (syntax check, run configuration) for TaskJuggler files.
        """.trimIndent()
    }
    // Credentials come from the environment (GitHub secrets in .github/workflows/release.yml).
    signing {
        certificateChain = providers.environmentVariable("CERTIFICATE_CHAIN")
        privateKey = providers.environmentVariable("PRIVATE_KEY")
        password = providers.environmentVariable("PRIVATE_KEY_PASSWORD")
    }
    publishing {
        token = providers.environmentVariable("PUBLISH_TOKEN")
    }
    pluginVerification {
        ides {
            recommended()
        }
    }
}

val basePackagePath = "fr/ledcom/tj3/taskjugglerplugin"

val generateTJLexer = tasks.register<GenerateLexerTask>("generateTJLexer") {
    sourceFile.set(file("src/main/grammars/TaskJuggler.flex"))
    targetRootOutputDir.set(generatedLexerRoot)
    purgeOldFiles.set(true)
}

val generateTJParser = tasks.register<GenerateParserTask>("generateTJParser") {
    sourceFile.set(file("src/main/grammars/TaskJuggler.bnf"))
    targetRootOutputDir.set(generatedParserRoot)
    pathToParser.set("$basePackagePath/TJParser.java")
    pathToPsiRoot.set("$basePackagePath/language/psi")
    purgeOldFiles.set(true)
}

tasks {
    withType<JavaCompile> {
        dependsOn(generateTJLexer, generateTJParser)
        // Report use of deprecated platform/JDK APIs; generated lexer/parser sources are included.
        options.compilerArgs.addAll(listOf("-Xlint:deprecation", "-Xlint:removal"))
    }
    // verifyPluginSignature reads signPlugin's output without declaring it (IntelliJ Platform Gradle Plugin 2.20.1),
    // which Gradle 9 rejects.
    verifyPluginSignature {
        dependsOn(signPlugin)
    }
}
